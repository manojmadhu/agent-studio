export type IconName = keyof typeof ICONS | (string & {});

export interface IconProps {
  name: IconName;
  size?: number;
  className?: string;
  title?: string;
}

/** Decorative by default (aria-hidden); pass `title` for a labelled icon. */
export function Icon({ name, size = 16, className = '', title }: IconProps) {
  const C = ICONS[name];
  if (!C) return null;
  return <C size={size} className={`i ${className}`.trim()} aria-hidden={title ? undefined : true} aria-label={title} role={title ? 'img' : undefined} focusable={false} />;
}

export const hasIcon = (n: string): boolean => n in ICONS;
